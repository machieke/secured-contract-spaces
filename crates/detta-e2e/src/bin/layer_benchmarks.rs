//! Cross-layer cost and latency benchmark harness for DeTTa.
//!
//! Self-contained (no external bench crate): measures wall-clock latency with
//! `std::time::Instant` over warmed iterations and reports byte-cost (canonical
//! `serde_json` size) and DA data-gas for each layer. Emits Markdown to stdout.
//!
//! Run with: `cargo run -p detta-e2e --bin layer_benchmarks --release`

use std::collections::BTreeSet;
use std::time::Instant;

use detta_consensus::{
    verify_data_availability_certificate, verify_data_availability_payload, ConsensusCluster,
};
use detta_core::{Argument, Block, DataAvailabilityCommitment, DeTTaState, Method, Transaction};
use detta_da::{
    assigned_custody_share_indices, derive_sample_schedule, prove_share_inclusion,
    verify_manifest_commits_payload, verify_share_inclusion_proof, DaAvailabilityCertificate,
    DaAvailabilityVote, DaCodingFraudProof, DaManifest, DaNamespace, DaNamespaceSection, DaPayload,
    DaProductionProfile, DaRecord, DaShareSet,
};
use detta_protocol::{decode_message, encode_message, ProtocolMessage};
use detta_storage::FileStorage;

const CHAIN_ID: &str = "detta-bench";
const TARGET_SHARE_SIZE: usize = 4096;
const SIZES: [usize; 3] = [16, 64, 256];

fn main() {
    if std::env::args().any(|a| a == "--check") {
        std::process::exit(run_perf_smoke());
    }

    println!("# DeTTa Layer Cost & Latency Benchmarks\n");
    println!(
        "Generated by `cargo run -p detta-e2e --bin layer_benchmarks --release`.\n\
         Latency is mean wall-clock per operation over warmed iterations; byte cost is\n\
         canonical `serde_json` serialized size; DA gas uses `DaProductionProfile::v1`\n\
         (1024-byte units).\n"
    );

    for &n in &SIZES {
        run_workload(n);
    }
    println!("\n_End of generated benchmark output._");
}

/// CI perf-smoke. Asserts hardware-independent invariants: deterministic cost
/// (byte/gas) relationships that are exact across runs; latency ratios measured
/// within the same process, so absolute CPU speed cancels out and only a real
/// algorithmic regression trips a check; and one coarse absolute backstop
/// (overridable) against catastrophic blowups. Returns a process exit code
/// (0 = pass, 1 = fail).
fn run_perf_smoke() -> i32 {
    println!("# DeTTa perf-smoke\n");
    let mut failures = 0u32;

    // --- Deterministic cost invariants, checked at every workload size ---
    for &n in &SIZES {
        let c = Scenario::build(n).costs();
        failures += check(
            &format!("[{n}] DA data-gas == ceil(payload/1024)"),
            c.da_gas == (c.payload_bytes as u64).div_ceil(1024),
        );
        failures += check(
            &format!("[{n}] equal data/parity shares (encoded == 2*data)"),
            c.encoded_shares == 2 * c.original_shares,
        );
        failures += check(
            &format!("[{n}] share size <= target {TARGET_SHARE_SIZE}"),
            c.share_size as usize <= TARGET_SHARE_SIZE,
        );
        failures += check(
            &format!("[{n}] manifest is a compact commitment (< payload)"),
            c.manifest_bytes < c.payload_bytes && c.manifest_msg_bytes < c.payload_bytes,
        );
        failures += check(
            &format!("[{n}] certificate is small and bounded (< 1 KiB)"),
            c.cert_bytes < 1024,
        );
        failures += check(
            &format!("[{n}] coding-fraud proof embeds data shares (>= payload)"),
            c.proof_bytes >= c.payload_bytes,
        );
        failures += check(
            &format!("[{n}] block wire message tracks payload (0.5x..2x)"),
            c.block_msg_bytes * 2 > c.payload_bytes && c.block_msg_bytes < c.payload_bytes * 2,
        );
    }

    // --- Latency-ratio invariants at the largest size (timings well above the
    // timer floor, ratios robust to CI jitter) ---
    let scenario = Scenario::build(*SIZES.last().unwrap());
    let rows = scenario.latency_rows();
    let ns = |name: &str| -> f64 {
        rows.iter()
            .find(|r| r.0 == name)
            .map(|r| r.1)
            .unwrap_or_else(|| panic!("missing latency row: {name}"))
    };

    let reconstruct = ns("da: reconstruct payload (full share set)");
    let verify_payload = ns("consensus: verify_data_availability_payload");
    let build_shares = ns("da: build share set (Reed-Solomon)");

    failures += check(
        "manifest_hash << full reconstruct (>=5x cheaper)",
        ns("da: manifest_hash") * 5.0 < reconstruct,
    );
    failures += check(
        "certificate verify << full payload verify (>=5x cheaper)",
        ns("consensus: verify_data_availability_certificate") * 5.0 < verify_payload,
    );
    failures += check(
        "sample schedule << full reconstruct (>=3x cheaper)",
        ns("da: sample schedule (3 samples)") * 3.0 < reconstruct,
    );
    failures += check(
        "custody assignment << full reconstruct (>=3x cheaper)",
        ns("da: custody assignment") * 3.0 < reconstruct,
    );
    failures += check(
        "manifest encode << share-set build (>=10x cheaper)",
        ns("protocol: encode DaManifest") * 10.0 < build_shares,
    );
    failures += check(
        "payload-binding cost ~ one RS pass (0.2x..5x of share-set build)",
        {
            let bind = ns("da: verify_manifest_commits_payload");
            bind > build_shares * 0.2 && bind < build_shares * 5.0
        },
    );

    // --- Coarse absolute backstop (overridable for slow runners) ---
    let max_ms: f64 = std::env::var("DETTA_PERF_SMOKE_MAX_MS")
        .ok()
        .and_then(|v| v.parse().ok())
        .unwrap_or(2_000.0);
    failures += check(
        &format!("verify_data_availability_payload < {max_ms:.0} ms backstop"),
        verify_payload / 1_000_000.0 < max_ms,
    );

    if failures > 0 {
        println!("\nperf-smoke FAILED: {failures} check(s) regressed");
        return 1;
    }
    println!("\nperf-smoke OK");
    0
}

fn check(label: &str, ok: bool) -> u32 {
    println!("{} {label}", if ok { "PASS" } else { "FAIL" });
    u32::from(!ok)
}

fn run_workload(tx_count: usize) {
    let scenario = Scenario::build(tx_count);

    println!("## Workload: {tx_count} transfer transactions\n");
    scenario.print_cost_table();
    println!();
    scenario.print_latency_table();
    println!();
}

struct Scenario {
    tx_count: usize,
    block: Block,
    payload: DaPayload,
    payload_bytes: usize,
    manifest: DaManifest,
    share_set: DaShareSet,
    certificate: DaAvailabilityCertificate,
    active_validators: BTreeSet<String>,
    quorum: usize,
    votes: Vec<DaAvailabilityVote>,
    coding_proof: DaCodingFraudProof,
}

impl Scenario {
    fn build(tx_count: usize) -> Self {
        let mut state = DeTTaState::new(CHAIN_ID);
        state
            .deploy_token(
                "TokenA",
                "USDC",
                vec![("Alice".into(), 1_000_000_000), ("Bob".into(), 1_000)],
            )
            .expect("token genesis should deploy");

        let transactions: Vec<Transaction> = (0..tx_count)
            .map(|i| Transaction {
                chain_id: CHAIN_ID.into(),
                tx_hash: format!("bench-tx-{i}"),
                sender: "Alice".into(),
                nonce: i as u64,
                valid_until_height: None,
                target: "TokenA".into(),
                method: Method::Transfer,
                args: vec![
                    Argument::Principal("Bob".into()),
                    Argument::Asset("USDC".into()),
                    Argument::Amount(1),
                ],
                signature_ok: true,
                budget: 1_000_000,
            })
            .collect();

        let (mut block, _next_state) =
            state.build_block(1, transactions, 1_000, "validator-1", "bench-cert:1");

        let payload = da_payload_for_block(&block);
        let payload_bytes = serde_json::to_vec(&payload)
            .expect("payload serializes")
            .len();

        // Execution block hash is computed without the DA commitment, matching the
        // consensus binding (`execution_block_hash_for_da`).
        let mut execution_block = block.clone();
        execution_block.header.data_availability = None;
        let execution_block_hash = execution_block.block_hash();

        let share_set = DaShareSet::from_payload_reed_solomon_with_target_share_size(
            &payload,
            &execution_block_hash,
            TARGET_SHARE_SIZE,
        )
        .expect("reed-solomon share set builds");
        let manifest = share_set.manifest.clone();

        let signers = ["validator-1", "validator-2", "validator-3"];
        let certificate = DaAvailabilityCertificate::from_manifest(
            &manifest,
            signers.iter().map(|s| s.to_string()),
        )
        .expect("certificate builds");

        block.header.data_availability = Some(DataAvailabilityCommitment {
            payload_root: manifest.payload_hash.clone(),
            manifest_hash: manifest.manifest_hash().expect("manifest hash"),
            share_root: manifest.share_root.clone(),
            certificate_hash: Some(certificate.certificate_hash().expect("certificate hash")),
        });

        let active_validators: BTreeSet<String> = signers.iter().map(|s| s.to_string()).collect();
        let quorum = 2;

        let profile = DaProductionProfile::v1();
        let votes: Vec<DaAvailabilityVote> = signers
            .iter()
            .map(|validator| {
                let custody = assigned_custody_share_indices(
                    &manifest,
                    validator,
                    profile.min_custody_share_count,
                )
                .expect("custody indices");
                DaAvailabilityVote::from_manifest_with_custody(
                    &manifest,
                    *validator,
                    custody,
                    Vec::<u32>::new(),
                )
                .expect("custody vote")
            })
            .collect();

        // A coding-fraud proof against a payload-hash-forged manifest, for the
        // fraud-detection cost/latency row.
        let mut forged = manifest.clone();
        forged.payload_hash = "11".repeat(32);
        let forged_manifest_hash = forged.manifest_hash().expect("forged manifest hash");
        let data_shares: Vec<_> = share_set
            .shares
            .iter()
            .filter(|share| share.index < forged.original_share_count)
            .cloned()
            .map(|mut share| {
                share.manifest_hash = forged_manifest_hash.clone();
                share
            })
            .collect();
        let coding_proof =
            DaCodingFraudProof::from_committed_data_shares(&forged, &data_shares, "reporter-1")
                .expect("coding fraud proof builds");

        Self {
            tx_count,
            block,
            payload,
            payload_bytes,
            manifest,
            share_set,
            certificate,
            active_validators,
            quorum,
            votes,
            coding_proof,
        }
    }

    fn costs(&self) -> Costs {
        let profile = DaProductionProfile::v1();
        Costs {
            payload_bytes: self.payload_bytes,
            da_gas: profile
                .data_gas_for_bytes(self.payload_bytes as u64)
                .expect("da gas"),
            manifest_bytes: serde_json::to_vec(&self.manifest).unwrap().len(),
            original_shares: self.manifest.original_share_count,
            encoded_shares: self.manifest.encoded_share_count,
            share_size: self.manifest.share_size_bytes,
            single_share_bytes: self
                .share_set
                .shares
                .first()
                .map(|s| s.bytes.len())
                .unwrap_or(0),
            cert_bytes: serde_json::to_vec(&self.certificate).unwrap().len(),
            proof_bytes: serde_json::to_vec(&self.coding_proof).unwrap().len(),
            block_msg_bytes: encode_message(&ProtocolMessage::Block(Box::new(self.block.clone())))
                .expect("block message encodes")
                .len(),
            manifest_msg_bytes: encode_message(&ProtocolMessage::DaManifest(Box::new(
                self.manifest.clone(),
            )))
            .expect("manifest message encodes")
            .len(),
        }
    }

    fn print_cost_table(&self) {
        let c = self.costs();
        println!("### Cost (bytes / gas)\n");
        println!("| Metric | Value |");
        println!("| --- | ---: |");
        println!("| DA payload (canonical JSON) | {} B |", c.payload_bytes);
        println!("| DA payload data-gas (1 KiB units) | {} |", c.da_gas);
        println!("| DA manifest | {} B |", c.manifest_bytes);
        println!(
            "| Encoded shares (data + parity) | {} ( {} + {} ) |",
            c.encoded_shares,
            c.original_shares,
            c.encoded_shares - c.original_shares
        );
        println!("| Share size | {} B |", c.share_size);
        println!("| Single share payload | {} B |", c.single_share_bytes);
        println!("| DA availability certificate | {} B |", c.cert_bytes);
        println!("| DA coding-fraud proof | {} B |", c.proof_bytes);
        println!("| Wire: Block message | {} B |", c.block_msg_bytes);
        println!("| Wire: DaManifest message | {} B |", c.manifest_msg_bytes);
    }

    fn print_latency_table(&self) {
        println!("### Latency (mean per operation)\n");
        println!("| Operation | Mean | Throughput |");
        println!("| --- | ---: | ---: |");
        for (name, mean_ns, ops_per_sec) in self.latency_rows() {
            println!(
                "| {name} | {} | {} |",
                fmt_time(mean_ns),
                fmt_ops(ops_per_sec)
            );
        }
    }

    fn latency_rows(&self) -> Vec<(&'static str, f64, f64)> {
        let mut rows: Vec<(&str, f64, f64)> = Vec::new();

        // --- Core / execution layer ---
        {
            let mut state = DeTTaState::new(CHAIN_ID);
            state
                .deploy_token(
                    "TokenA",
                    "USDC",
                    vec![("Alice".into(), 1_000_000_000), ("Bob".into(), 1_000)],
                )
                .unwrap();
            let txs = self.block.transactions.clone();
            rows.push(measure("core: build_block (execute N txs)", 50, || {
                let _ = state.build_block(1, txs.clone(), 1_000, "validator-1", "c");
            }));
        }
        {
            let mut applier = DeTTaState::new(CHAIN_ID);
            applier
                .deploy_token(
                    "TokenA",
                    "USDC",
                    vec![("Alice".into(), 1_000_000_000), ("Bob".into(), 1_000)],
                )
                .unwrap();
            let block = self.block.clone();
            rows.push(measure("core: apply_block", 50, || {
                let mut s = applier.clone();
                let _ = s.apply_block(&block);
            }));
        }

        // --- DA layer ---
        let block_hash = {
            let mut eb = self.block.clone();
            eb.header.data_availability = None;
            eb.block_hash()
        };
        rows.push(measure("da: build share set (Reed-Solomon)", 50, || {
            let _ = DaShareSet::from_payload_reed_solomon_with_target_share_size(
                &self.payload,
                &block_hash,
                TARGET_SHARE_SIZE,
            )
            .unwrap();
        }));
        rows.push(measure("da: manifest_hash", 200, || {
            let _ = self.manifest.manifest_hash().unwrap();
        }));
        rows.push(measure(
            "da: reconstruct payload (full share set)",
            50,
            || {
                let _ = self.share_set.reconstruct_payload().unwrap();
            },
        ));
        rows.push(measure("da: verify_manifest_commits_payload", 50, || {
            verify_manifest_commits_payload(&self.manifest, &self.payload).unwrap();
        }));
        rows.push(measure("da: custody assignment", 500, || {
            let _ = assigned_custody_share_indices(&self.manifest, "validator-1", 2).unwrap();
        }));
        rows.push(measure("da: sample schedule (3 samples)", 500, || {
            let _ = derive_sample_schedule(&self.manifest, b"client-randomness", 3).unwrap();
        }));
        {
            let proof = prove_share_inclusion(&self.manifest, 0).unwrap();
            let share = self
                .share_set
                .shares
                .iter()
                .find(|s| s.index == 0)
                .unwrap()
                .clone();
            rows.push(measure("da: prove share inclusion", 500, || {
                let _ = prove_share_inclusion(&self.manifest, 0).unwrap();
            }));
            rows.push(measure("da: verify share inclusion proof", 500, || {
                verify_share_inclusion_proof(&self.manifest, &share, &proof).unwrap();
            }));
        }
        rows.push(measure("da: build coding-fraud proof", 50, || {
            let mut forged = self.manifest.clone();
            forged.payload_hash = "11".repeat(32);
            let h = forged.manifest_hash().unwrap();
            let shares: Vec<_> = self
                .share_set
                .shares
                .iter()
                .filter(|s| s.index < forged.original_share_count)
                .cloned()
                .map(|mut s| {
                    s.manifest_hash = h.clone();
                    s
                })
                .collect();
            let _ = DaCodingFraudProof::from_committed_data_shares(&forged, &shares, "r").unwrap();
        }));
        {
            let forged = {
                let mut f = self.manifest.clone();
                f.payload_hash = "11".repeat(32);
                f
            };
            rows.push(measure("da: verify coding-fraud proof", 100, || {
                self.coding_proof.validate(&forged).unwrap();
            }));
        }

        // --- Consensus layer ---
        rows.push(measure(
            "consensus: verify_data_availability_payload",
            50,
            || {
                verify_data_availability_payload(&self.block, &self.payload, &self.manifest)
                    .unwrap();
            },
        ));
        rows.push(measure(
            "consensus: verify_data_availability_certificate",
            200,
            || {
                verify_data_availability_certificate(
                    &self.block,
                    &self.manifest,
                    &self.certificate,
                    &self.active_validators,
                    self.quorum,
                )
                .unwrap();
            },
        ));
        rows.push(measure("consensus: certificate from votes", 100, || {
            let _ = ConsensusCluster::data_availability_certificate_from_votes(
                &self.manifest,
                self.votes.clone(),
                self.quorum,
            )
            .unwrap();
        }));

        // --- Storage layer (filesystem) ---
        {
            let dir = std::env::temp_dir().join(format!(
                "detta-bench-{}-{}",
                self.tx_count,
                std::process::id()
            ));
            let _ = std::fs::remove_dir_all(&dir);
            let storage = FileStorage::open(&dir).expect("storage opens");
            let share_set = self.share_set.clone();
            let manifest_hash = self.manifest.manifest_hash().unwrap();
            rows.push(measure("storage: commit DA share set", 30, || {
                let _ = storage.commit_da_share_set(&share_set).unwrap();
            }));
            rows.push(measure("storage: load DA share set", 30, || {
                let _ = storage.load_da_share_set(&manifest_hash).unwrap();
            }));
            let _ = std::fs::remove_dir_all(&dir);
        }

        // --- Protocol / wire layer ---
        {
            let msg = ProtocolMessage::DaManifest(Box::new(self.manifest.clone()));
            let encoded = encode_message(&msg).unwrap();
            rows.push(measure("protocol: encode DaManifest", 500, || {
                let _ = encode_message(&msg).unwrap();
            }));
            rows.push(measure("protocol: decode DaManifest", 500, || {
                let _ = decode_message(&encoded).unwrap();
            }));
        }

        rows
    }
}

struct Costs {
    payload_bytes: usize,
    da_gas: u64,
    manifest_bytes: usize,
    original_shares: u32,
    encoded_shares: u32,
    share_size: u32,
    single_share_bytes: usize,
    cert_bytes: usize,
    proof_bytes: usize,
    block_msg_bytes: usize,
    manifest_msg_bytes: usize,
}

fn da_payload_for_block(block: &Block) -> DaPayload {
    let namespaces = vec![
        DaNamespaceSection::new(
            DaNamespace::new("detta.block").unwrap(),
            vec![DaRecord::BlockHeader(Box::new(block.header.clone()))],
        )
        .unwrap(),
        DaNamespaceSection::new(
            DaNamespace::new("detta.tx").unwrap(),
            block
                .transactions
                .iter()
                .cloned()
                .map(DaRecord::SignedTransaction)
                .collect(),
        )
        .unwrap(),
        DaNamespaceSection::new(
            DaNamespace::new("detta.receipt").unwrap(),
            block
                .receipts
                .iter()
                .cloned()
                .map(DaRecord::Receipt)
                .collect(),
        )
        .unwrap(),
    ];
    DaPayload::new(
        block.header.chain_id.clone(),
        block.header.height,
        block.header.previous_block_hash.clone(),
        namespaces,
    )
    .unwrap()
}

fn measure<F: FnMut()>(name: &'static str, iters: u32, mut f: F) -> (&'static str, f64, f64) {
    // Warmup.
    for _ in 0..(iters / 5).max(1) {
        f();
    }
    let start = Instant::now();
    for _ in 0..iters {
        f();
    }
    let elapsed = start.elapsed();
    let mean_ns = elapsed.as_nanos() as f64 / iters as f64;
    let ops_per_sec = if mean_ns > 0.0 {
        1_000_000_000.0 / mean_ns
    } else {
        f64::INFINITY
    };
    (name, mean_ns, ops_per_sec)
}

fn fmt_time(ns: f64) -> String {
    if ns >= 1_000_000.0 {
        format!("{:.2} ms", ns / 1_000_000.0)
    } else if ns >= 1_000.0 {
        format!("{:.2} µs", ns / 1_000.0)
    } else {
        format!("{ns:.0} ns")
    }
}

fn fmt_ops(ops: f64) -> String {
    if ops >= 1_000_000.0 {
        format!("{:.2} M/s", ops / 1_000_000.0)
    } else if ops >= 1_000.0 {
        format!("{:.1} K/s", ops / 1_000.0)
    } else {
        format!("{ops:.0} /s")
    }
}
